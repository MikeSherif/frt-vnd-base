const SAMPLE_PDF = '/samples/lab1.pdf'
const APPENDIX = '/samples/appendix.xlsx'

function pdfFile(id, name, hash = `hash-${id}`) {
  return {
    id,
    name,
    mime: 'application/pdf',
    size: 215408,
    url: SAMPLE_PDF,
    hash,
    isSignedOriginal: true,
  }
}

function basisFile(id) {
  return {
    id: `${id}-basis`,
    name: `osnovanie-${id}.pdf`,
    mime: 'application/pdf',
    size: 215408,
    url: SAMPLE_PDF,
    hash: `basis-${id}`,
    isSignedOriginal: true,
  }
}

function revision({
  id,
  number,
  effectiveFrom,
  effectiveTo = null,
  publishedAt,
  isSubstantive = true,
  confirmedStart = true,
  incomplete = false,
  incompleteReason = '',
  hash,
  name,
  attachments = [],
}) {
  return {
    id,
    number,
    effectiveFrom,
    effectiveTo,
    confirmedStart,
    isSubstantive,
    publishedAt,
    incomplete,
    incompleteReason,
    file: name ? pdfFile(`${id}-file`, name, hash) : null,
    basisFile: confirmedStart ? basisFile(id) : null,
    attachments,
    basisDetails: confirmedStart ? `Приказ, редакция ${number}` : '',
    locked: true,
  }
}

function baseDocument(partial) {
  const document = {
    summary: '',
    keywords: [],
    governingBody: 'Правление Фонда',
    adoptionDocKind: 'Приказ',
    adoptionDocDetails: '',
    published: true,
    version: 1,
    nextCheckAt: '',
    overlapConfirmed: false,
    functionLinks: [],
    documentLinks: [],
    relevanceEvents: [],
    changelog: [],
    processOwnerDeptId: partial.ownerDeptId ?? '',
    ...partial,
  }
  document.functionLinks = document.functionLinks.map((link) => ({ locked: true, ...link }))
  document.documentLinks = document.documentLinks.map((link) => ({ locked: true, ...link }))
  document.relevanceEvents = document.relevanceEvents.map((event) => ({ locked: true, ...event }))
  return document
}

